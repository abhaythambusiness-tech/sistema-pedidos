require('dotenv').config();
const express = require('express');
const cors = require('cors');
const path = require('path');
const app = express();
app.use(cors());
app.use(express.json({ limit: '2mb' }));
app.use(express.static(path.join(__dirname, '..', 'public')));
require('./seed')();
app.use('/api/auth', require('./routes/auth'));
app.use('/api/products', require('./routes/products'));
app.use('/api/ingredients', require('./routes/ingredients'));
app.use('/api/orders', require('./routes/orders'));
app.use('/api/print', require('./routes/print'));
app.use('/api/vapi', require('./routes/vapi'));
app.get('/api/health', (_req, res) => res.json({ ok: true, uptime: process.uptime() }));
app.use((err, _req, res, _next) => { console.error('[error]', err); res.status(500).json({ error: 'Error interno' }); });
const PORT = process.env.PORT || 3000;
app.listen(PORT, () => { console.log(`✅ Servidor en http://localhost:${PORT}`); console.log(`   Webhook Vapi: POST http://localhost:${PORT}/api/vapi/webhook`); });
